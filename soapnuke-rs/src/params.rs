#[derive(Clone, Debug, Eq, PartialEq)]
pub enum SamplingTarget {
    Count(u64),
    Ratio { numerator: u128, denominator: u128 },
}

impl SamplingTarget {
    pub fn resolve(&self, retained: u64) -> u64 {
        match self {
            SamplingTarget::Count(count) => *count,
            SamplingTarget::Ratio {
                numerator,
                denominator,
            } => ((retained as u128 * *numerator) / *denominator) as u64,
        }
    }
}

